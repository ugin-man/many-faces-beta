const fragments = Object.keys(english).sort((a, b) => b.length - a.length);
const pattern = new RegExp(fragments.map(key => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");

export function normalizeLanguage(value: unknown): Language { return value === "ja" ? "ja" : "en"; }

/** Translate stored engine messages at render time so switching never restarts processing. */
export function translate(text: string, language: Language): string {
  if (language === "ja") return text;
  if (Object.hasOwn(english, text)) return english[text];
  return text
    .replace(/「(.+)」で(\d+)秒以上進捗がありません。処理を停止しました。/g, (_, phase, seconds) => `No progress during “${translate(phase, language)}” for ${seconds} seconds. Processing stopped.`)
    .replace(/入力映像を再生できませんでした（media code (\d+)）。/g, "Could not play the video input (media code $1).")
    .replace(/解析エンジンの準備が進んでいません（(.*?)）。/g, "Analysis engine setup stalled ($1).")
    .replace(pattern, key => english[key]);
}
